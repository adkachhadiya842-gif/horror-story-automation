
"""
Cinematic Horror Story - Image Generator
Generates character, location, entity and scene reference images
using the official Google Gen AI Python SDK.
"""

import io
import json
import logging
import re
import time
from pathlib import Path

from PIL import Image
from google import genai
from google.genai import types

from scripts.utils import (
    PROJECT_ROOT,
    OUTPUT_DIR,
    load_config,
    get_api_key,
    create_project_directories,
    save_json,
)


LOGGER = logging.getLogger(__name__)

ANALYSIS_PATH = Path(OUTPUT_DIR) / "story_analysis.json"
ASSET_ROOT = Path(OUTPUT_DIR) / "assets"

CHARACTER_DIR = ASSET_ROOT / "characters"
LOCATION_DIR = ASSET_ROOT / "locations"
ENTITY_DIR = ASSET_ROOT / "entities"
SCENE_DIR = ASSET_ROOT / "scenes"

STYLE = (
    "Premium cinematic photorealistic 3D horror film aesthetic, "
    "extremely detailed realistic textures, natural anatomy, "
    "cinematic composition, dramatic film lighting, "
    "realistic Indian environments when appropriate, "
    "professional horror movie cinematography, "
    "high visual fidelity, widescreen 16:9 composition. "
    "No text, no captions, no logos, no watermarks."
)


def setup_logging():
    """Configure image generator logging."""

    log_dir = Path(OUTPUT_DIR) / "logs"
    log_dir.mkdir(parents=True, exist_ok=True)

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s | %(levelname)s | %(message)s",
        handlers=[
            logging.StreamHandler(),
            logging.FileHandler(
                log_dir / "image_generator.log",
                encoding="utf-8"
            ),
        ],
    )


def safe_filename(value):
    """Convert names into safe filenames."""

    value = str(value).strip().lower()
    value = re.sub(r"[^\w-]+", "_", value)
    value = value.strip("_")

    return value[:70] or "unnamed"


def get_setting(config, section, key, default):
    """Safely retrieve configuration values."""

    return config.get(section, {}).get(key, default)


def load_analysis():
    """Load story analysis generated by story_analyzer.py."""

    if not ANALYSIS_PATH.exists():
        raise FileNotFoundError(
            f"Story analysis not found: {ANALYSIS_PATH}. "
            "Run story_analyzer.py first."
        )

    with open(ANALYSIS_PATH, "r", encoding="utf-8") as file:
        analysis = json.load(file)

    if not isinstance(analysis, dict):
        raise ValueError("Story analysis must be a JSON object.")

    if not isinstance(analysis.get("scenes"), list):
        raise ValueError("Story analysis must contain a scenes list.")

    if not analysis["scenes"]:
        raise ValueError("No scenes found in story analysis.")

    return analysis


def create_client():
    """Initialize the official Google Gen AI client."""

    api_key = get_api_key()

    if not api_key:
        raise ValueError("GEMINI_API_KEY is missing.")

    return genai.Client(api_key=api_key)


def build_prompt(category, item, analysis=None):
    """Build cinematic image prompts."""

    analysis = analysis or {}

    if category == "character":
        return f"""
Create a professional CHARACTER REFERENCE IMAGE for a cinematic
Hindi horror film.

CHARACTER NAME: {item.get('name', 'Unknown')}
AGE: {item.get('age', 'Not specified')}
APPEARANCE: {item.get('appearance', '')}
CLOTHING: {item.get('clothing', '')}
PERSONALITY: {item.get('personality', '')}
ROLE: {item.get('role', '')}
CONTINUITY: {item.get('visual_consistency_notes', '')}

Show the same character in a professional reference composition:
full body, front view, three-quarter view and side profile,
with natural facial details and consistent clothing.

Maintain realistic human proportions and identity.

Visual style: {STYLE}
"""

    if category == "location":
        return f"""
Create a cinematic LOCATION REFERENCE IMAGE.

LOCATION: {item.get('name', 'Unknown')}
DESCRIPTION: {item.get('description', '')}
ATMOSPHERE: {item.get('atmosphere', '')}
LIGHTING: {item.get('lighting', '')}
CONTINUITY: {item.get('visual_consistency_notes', '')}

Show a detailed establishing view of the environment.
Preserve its architectural style, geography, weather,
lighting and recognizable visual features.

Visual style: {STYLE}
"""

    if category == "entity":
        return f"""
Create a cinematic SUPERNATURAL ENTITY REFERENCE IMAGE.

ENTITY: {item.get('name', 'Unknown')}
DESCRIPTION: {item.get('description', '')}
BEHAVIOR: {item.get('behavior', '')}
CONTINUITY: {item.get('visual_consistency_notes', '')}

Create a frightening but visually coherent supernatural
entity. Preserve its appearance and physical characteristics
for consistency in all subsequent scenes.

Visual style: {STYLE}
"""

    if category == "scene":
        return f"""
Create ONE cinematic widescreen still image for a Hindi
horror movie.

STORY TITLE: {analysis.get('title', 'Horror Story')}
SCENE NUMBER: {item.get('scene_number', '')}

STORY EVENT:
{item.get('story_event', '')}

CHARACTERS PRESENT:
{', '.join(map(str, item.get('characters_present', [])))}

LOCATION:
{item.get('location', '')}

VISUAL DESCRIPTION:
{item.get('visual_description', '')}

CAMERA ANGLE:
{item.get('camera_angle', '')}

LIGHTING:
{item.get('lighting', '')}

ATMOSPHERE:
{item.get('atmosphere', '')}

IMPORTANT:
Follow the original story event exactly.
Do not invent additional characters or events.
Maintain character appearance and location continuity.
Do not combine multiple story moments into one image.
Use a single cinematic film frame.

Visual style: {STYLE}
"""

    raise ValueError(f"Unknown image category: {category}")


def extract_image(response):
    """Extract generated image bytes from Gemini response."""

    if not response.candidates:
        raise RuntimeError("Gemini returned no candidates.")

    candidate = response.candidates[0]

    if not candidate.content or not candidate.content.parts:
        raise RuntimeError("Gemini returned no image content.")

    for part in candidate.content.parts:
        if part.inline_data and part.inline_data.data:
            return part.inline_data.data

    raise RuntimeError(
        "No image data found in Gemini response. "
        "Check model availability and safety filters."
    )


def save_generated_image(image_bytes, output_path):
    """Validate and save the generated image as PNG."""

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with Image.open(io.BytesIO(image_bytes)) as image:
        image.load()
        image.convert("RGB").save(output_path, format="PNG")

    LOGGER.info("Image saved: %s", output_path)

    return str(output_path)


def generate_image(
    client,
    prompt,
    output_path,
    model,
    aspect_ratio="16:9",
    max_retries=3,
    retry_delay=10,
    reference_paths=None,
):
    """Generate one image with retry support."""

    contents = []

    # Supply existing reference images for visual consistency.
    for reference_path in reference_paths or []:
        reference_path = Path(reference_path)

        if reference_path.exists():
            with Image.open(reference_path) as image:
                image_format = image.format or "PNG"
                mime_type = (
                    "image/jpeg"
                    if image_format.upper() in ("JPEG", "JPG")
                    else "image/png"
                )

            contents.append(
                types.Part.from_bytes(
                    data=reference_path.read_bytes(),
                    mime_type=mime_type,
                )
            )

    contents.append(prompt)

    for attempt in range(1, max_retries + 1):
        try:
            LOGGER.info(
                "Generating %s (attempt %s/%s)",
                output_path,
                attempt,
                max_retries,
            )

            response = client.models.generate_content(
                model=model,
                contents=contents,
                config=types.GenerateContentConfig(
                    response_modalities=["IMAGE"],
                    image_config=types.ImageConfig(
                        aspect_ratio=aspect_ratio
                    ),
                    candidate_count=1,
                ),
            )

            image_bytes = extract_image(response)

            return save_generated_image(
                image_bytes,
                output_path
            )

        except Exception as error:
            LOGGER.warning(
                "Image generation failed: %s",
                error
            )

            if attempt == max_retries:
                LOGGER.error(
                    "Maximum retries reached for %s",
                    output_path
                )
                raise

            time.sleep(retry_delay * attempt)

    return None


def generate_references(client, analysis, model, config):
    """Generate character, location and entity references."""

    references = {
        "characters": {},
        "locations": {},
        "entities": {},
    }

    collections = [
        ("characters", CHARACTER_DIR, "character"),
        ("locations", LOCATION_DIR, "location"),
        ("entities", ENTITY_DIR, "entity"),
    ]

    max_retries = int(
        get_setting(config, "generation", "max_retries", 3)
    )

    retry_delay = int(
        get_setting(
            config,
            "generation",
            "retry_delay_seconds",
            10
        )
    )

    for collection_name, folder, category in collections:

        items = analysis.get(collection_name, [])

        if not isinstance(items, list):
            LOGGER.warning(
                "Invalid %s collection. Skipping.",
                collection_name
            )
            continue

        for index, item in enumerate(items, start=1):

            if not isinstance(item, dict):
                continue

            name = item.get("name") or f"{category}_{index}"

            filename = (
                f"{index:03d}_{safe_filename(name)}.png"
            )

            output_path = folder / filename

            prompt = build_prompt(
                category,
                item,
                analysis
            )

            try:
                image_path = generate_image(
                    client=client,
                    prompt=prompt,
                    output_path=output_path,
                    model=model,
                    aspect_ratio="16:9",
                    max_retries=max_retries,
                    retry_delay=retry_delay,
                )

                references[collection_name][name] = image_path

            except Exception:
                LOGGER.exception(
                    "Reference generation failed: %s",
                    name
                )

    return references


def select_scene_images(scenes, image_count):
    """Select scene images in original chronological order."""

    if len(scenes) <= image_count:
        return scenes

    if image_count <= 0:
        raise ValueError("image_count must be greater than zero.")

    indexes = [
        round(i * (len(scenes) - 1) / (image_count - 1))
        if image_count > 1 else 0
        for i in range(image_count)
    ]

    return [scenes[index] for index in indexes]


def get_scene_references(scene, references):
    """Find relevant character and location reference images."""

    selected = []

    character_map = references.get("characters", {})
    location_map = references.get("locations", {})
    entity_map = references.get("entities", {})

    present_characters = scene.get("characters_present", [])

    if isinstance(present_characters, list):
        for character in present_characters:
            if character in character_map:
                selected.append(character_map[character])

    location = scene.get("location")

    if location in location_map:
        selected.append(location_map[location])

    # Include entities only when their names occur in scene details.
    scene_text = json.dumps(
        scene,
        ensure_ascii=False
    ).lower()

    for name, path in entity_map.items():
        if str(name).lower() in scene_text:
            selected.append(path)

    return [
        path for path in selected
        if path and Path(path).exists()
    ]


def generate_scene_images(
    client,
    analysis,
    references,
    model,
    config,
):
    """Generate cinematic images in original story order."""

    scenes = analysis["scenes"]

    image_count = int(
        get_setting(config, "video", "image_count", 96)
    )

    if image_count <= 0:
        raise ValueError("Configured image_count must be positive.")

    selected_scenes = select_scene_images(
        scenes,
        image_count
    )

    max_retries = int(
        get_setting(config, "generation", "max_retries", 3)
    )

    retry_delay = int(
        get_setting(
            config,
            "generation",
            "retry_delay_seconds",
            10
        )
    )

    generated_scenes = []

    for index, scene in enumerate(selected_scenes, start=1):

        if not isinstance(scene, dict):
            continue

        scene_number = scene.get("scene_number", index)

        filename = (
            f"scene_{index:03d}_story_{scene_number}.png"
        )

        output_path = SCENE_DIR / filename

        prompt = build_prompt(
            "scene",
            scene,
            analysis
        )

        reference_paths = get_scene_references(
            scene,
            references
        )

        try:
            image_path = generate_image(
                client=client,
                prompt=prompt,
                output_path=output_path,
                model=model,
                aspect_ratio="16:9",
                max_retries=max_retries,
                retry_delay=retry_delay,
                reference_paths=reference_paths,
            )

            generated_scenes.append({
                "image_index": index,
                "scene_number": scene_number,
                "story_event": scene.get("story_event", ""),
                "image_path": image_path,
                "status": "success",
            })

        except Exception as error:
            LOGGER.exception(
                "Scene image failed: %s",
                scene_number
            )

            generated_scenes.append({
                "image_index": index,
                "scene_number": scene_number,
                "story_event": scene.get("story_event", ""),
                "image_path": None,
                "status": "failed",
                "error": str(error),
            })

    return generated_scenes


def main():
    """Run the complete image generation module."""

    setup_logging()

    LOGGER.info("Starting horror image generation.")

    create_project_directories()

    for folder in [
        CHARACTER_DIR,
        LOCATION_DIR,
        ENTITY_DIR,
        SCENE_DIR,
    ]:
        folder.mkdir(parents=True, exist_ok=True)

    config = load_config()
    analysis = load_analysis()
    client = create_client()

    model = get_setting(
        config,
        "generation",
        "image_model",
        "gemini-2.5-flash-image"
    )

    LOGGER.info("Using image model: %s", model)

    references = generate_references(
        client,
        analysis,
        model,
        config
    )

    scene_results = generate_scene_images(
        client,
        analysis,
        references,
        model,
        config
    )

    report = {
        "story_title": analysis.get("title", "Untitled"),
        "image_model": model,
        "reference_images": references,
        "scene_images": scene_results,
        "total_scenes_requested": len(scene_results),
        "successful_scene_images": sum(
            1 for item in scene_results
            if item["status"] == "success"
        ),
        "failed_scene_images": sum(
            1 for item in scene_results
            if item["status"] == "failed"
        ),
    }

    report_path = (
        Path(OUTPUT_DIR) / "image_generation_report.json"
    )

    save_json(report, report_path)

    LOGGER.info("Image generation completed.")
    LOGGER.info("Report saved: %s", report_path)


if __name__ == "__main__":
    main()
